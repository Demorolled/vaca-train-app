"""distiller — what other models actually built, ingested as multi-file tasks.

Every other sheet in the library is generated by this app or scraped from VACA's
exports. This one is different: it is other likely models' real work. The
Distiller (`~/Desktop/Distiller`) hands a brief to a model, the model plans and
writes the whole file set, and the real toolchain compiles and runs it; only then
is the record appended to a pool. Each record that built is one task here — the
files, the entry a model would be asked to write, and the output the harness saw.

Two things are deliberate:

  * a record that did not build is never imported, and neither is one whose plan
    came back empty — a writer that never saw a brief wrote an app nobody asked
    for, and it can build perfectly;
  * the sheet is kept apart from `app_tasks.jsonl`, which `appcorpus.ingest`
    rewrites from scratch. Rows that took a model minutes to build are not going
    to be deleted because an export changed.

Not in the five focus lanes? The rows are still kept: `library.load_tasks(
all_languages=True)` returns them, and `stats()` counts them as outside the cut.

    python3 -m trainapp.distiller --pool ~/Desktop/Distiller/workspace/pool.jsonl
"""
from __future__ import annotations

import argparse
import collections
import json
import os
from pathlib import Path

from . import appcorpus, library

ORIGIN = "distiller-build"
SHEET = "distiller_builds.jsonl"
DATASHEET = "distillation_datasheet.json"
DEFAULT_POOL = Path.home() / "Desktop" / "Distiller" / "workspace" / "pool.jsonl"

# The file a model is asked to write, when the pool has no usable plan entry.
ENTRY_NAMES = ("main", "index", "app", "program", "run")


def pool_path(explicit: str = "") -> Path:
    chosen = explicit or os.environ.get("DISTILLER_POOL") or ""
    return Path(chosen).expanduser() if chosen else DEFAULT_POOL


def sheet_path() -> Path:
    return library.library_dir() / SHEET


def _read_pool(path: Path) -> list[dict]:
    if not path.exists():
        return []
    records: list[dict] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(record, dict):
            records.append(record)
    return records


def _record_files(record: dict) -> list[dict]:
    files: list[dict] = []
    seen: set[str] = set()
    for raw in record.get("files") or []:
        if not isinstance(raw, dict):
            continue
        path = str(raw.get("path") or "").replace("\\", "/").strip()
        content = str(raw.get("content") or "")
        if not path or path in seen or not content.strip():
            continue
        if path.startswith("/") or ".." in Path(path).parts:
            continue
        seen.add(path)
        files.append({"path": path, "content": content})
    return files


def _empty_plan(record: dict) -> bool:
    """True when no attempt got a plan: the writer had no brief to work from."""
    attempts = [a for a in record.get("attempts") or [] if isinstance(a, dict)]
    if not attempts:
        return True
    for attempt in attempts:
        plan = attempt.get("plan_json") or {}
        if isinstance(plan, dict) and (str(plan.get("plan") or "").strip()
                                      or plan.get("files")):
            return False
    return True


def _entry_for(files: list[dict], record: dict) -> str:
    """The entry the plan named, else the file that looks like a program."""
    sources = [f["path"] for f in files
               if Path(f["path"]).suffix.lower() in appcorpus.SOURCE_SUFFIXES]
    if not sources:
        return ""
    for attempt in reversed(record.get("attempts") or []):
        plan = (attempt or {}).get("plan_json") or {}
        entry = str((plan or {}).get("entry") or "").replace("\\", "/").strip()
        if entry in sources:
            return entry
    for name in ENTRY_NAMES:
        for path in sources:
            if Path(path).stem.lower().startswith(name):
                return path
    return sources[0]


def _stdout_matched(record: dict) -> bool:
    for attempt in reversed(record.get("attempts") or []):
        verdict = (attempt or {}).get("stdout_match")
        if isinstance(verdict, bool):
            return verdict
    return False


def skip_reason(record: dict) -> str:
    """Why a pool record is not a library task, or "" when it is one."""
    if not record.get("ok"):
        return "did not build"
    if not _record_files(record):
        return "no files"
    if _empty_plan(record):
        return "the plan came back empty"
    task = record.get("task") or {}
    language = str(task.get("language") or "").strip().lower()
    if language not in appcorpus.SOURCE_SUFFIXES.values():
        return "unknown language"
    if not _entry_for(_record_files(record), record):
        return "no source file"
    return ""


def task_from_record(record: dict) -> dict | None:
    """One built pool record → one multi-file task, or None when unusable."""
    if skip_reason(record):
        return None
    files = _record_files(record)
    target = _entry_for(files, record)
    by_path = {f["path"]: f for f in files}
    if target not in by_path:
        return None
    language = appcorpus.SOURCE_SUFFIXES[Path(target).suffix.lower()]
    task = (record.get("task") or {})
    brief = str(task.get("brief") or "").strip()
    label = str(record.get("label") or record.get("model") or "unknown").strip()
    title = brief[:70].strip() or f"{language} app"
    tags = ["distiller", language, label]
    if _stdout_matched(record):
        tags.append("stdout-matched")
    return library._task(
        origin=ORIGIN,
        language=language,
        title=title,
        code=by_path[target]["content"],
        runnable=True,
        description=brief,
        tags=tags,
        category="scaffold",
        source=f"distiller:{label}",
        files=files,
        target=target,
    )


def _existing_keys() -> set[str]:
    keys = set()
    for task in library.load_tasks(all_languages=True):
        language = task.get("language", "")
        code = task.get("code", "")
        if code:
            keys.add(library._code_hash(language, code))
    return keys


def _write_sheet(rows: list[dict]) -> None:
    path = sheet_path()
    with path.open("a", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def copy_datasheet(source: str = "") -> str:
    """Keep the Distiller's own export beside the sheet it explains."""
    chosen = Path(source).expanduser() if source else None
    if not chosen or not chosen.exists():
        return ""
    out = library.library_dir() / DATASHEET
    out.write_text(chosen.read_text(encoding="utf-8"), encoding="utf-8")
    return str(out)


def ingest(pool: str = "", datasheet: str = "", dry_run: bool = False) -> dict:
    """Append every new built app from the pool; safe to run after every series."""
    records = _read_pool(pool_path(pool))
    existing = _existing_keys()
    rows: list[dict] = []
    skipped: collections.Counter = collections.Counter()
    for record in records:
        reason = skip_reason(record)
        if reason:
            skipped[reason] += 1
            continue
        task = task_from_record(record)
        if not task:
            skipped["no usable file set"] += 1
            continue
        key = library._code_hash(task["language"], task["code"])
        if key in existing:
            skipped["already in the library"] += 1
            continue
        existing.add(key)
        rows.append(task)

    by_language: collections.Counter = collections.Counter(t["language"] for t in rows)
    copied = "" if dry_run else copy_datasheet(datasheet)
    if rows and not dry_run:
        _write_sheet(rows)
    return {
        "pool": str(pool_path(pool)),
        "records": len(records),
        "added": len(rows),
        "by_language": dict(sorted(by_language.items())),
        "skipped": dict(sorted(skipped.items())),
        "sheet": str(sheet_path()),
        "datasheet": copied,
        "dry_run": dry_run,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Ingest the Distiller's built apps as multi-file library tasks")
    parser.add_argument("--pool", default="",
                        help="pool.jsonl (default: $DISTILLER_POOL or ~/Desktop/Distiller/workspace/pool.jsonl)")
    parser.add_argument("--datasheet", default="",
                        help="distillation_datasheet.json to keep beside the sheet")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    print(json.dumps(ingest(args.pool, args.datasheet, args.dry_run), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
